import numpy as np


class Algorithm:
    """
    Feasibility-first mixed-variable (mu+lambda) EA with an operator bandit and a
    linear surrogate of the constraint violations.
      - A ridge-regression model maps normalised design vectors to each constraint's violation.
        It is refitted on all evaluated points as the run proceeds.
      - Surrogate pre-screening: for each child slot, several candidates are generated by the
        chosen operator, and only the one with the lowest predicted weighted violation is
        evaluated. This reduces evaluations spent on infeasible points without spending budget.
      - Adaptive constraint weights combine cumulative violation rate, violation magnitude and
        an EMA of recent violation frequency.
      - Adaptive bisection repair toward the best feasible point, with a feasibility-driven rate.
      - Stagnation triggers coordinate intensification and an archive-elite restart.
    """

    def __init__(self, budget=10000, dim=10):
        self.budget = int(budget)
        self.dim = int(dim)

    def __call__(self, func):
        d = self.dim
        lb = np.asarray(func.bounds.lb, dtype=float).copy()
        ub = np.asarray(func.bounds.ub, dtype=float).copy()
        types = [str(t) for t in func.variable_types]
        n_values = getattr(func, "n_values", None)

        cont_mask = np.array([t == "continuous" for t in types], dtype=bool)
        cont_idx = np.where(cont_mask)[0]
        int_idx = np.where(~cont_mask)[0]
        is_bin = np.array([t == "binary" for t in types], dtype=bool)
        is_cat = np.array([t == "categorical" for t in types], dtype=bool)
        is_ord = np.array([t == "ordinal" for t in types], dtype=bool)

        nv = np.ones(d, dtype=int)
        for i in int_idx:
            nv[i] = int(n_values[i])
        cont_scale = (ub - lb) / 2.0
        span = np.maximum(ub - lb, 1e-12)

        cache = {}
        self.used = 0
        feas_archive = []
        all_x, all_v = [], []
        S = {"best": None, "W": None, "cnt": None, "mag": None, "ema": None,
             "n_seen": 0, "n_feas": 0, "B": None}

        def repair(x):
            x = np.clip(x, lb, ub)
            for i in int_idx:
                x[i] = np.clip(np.round(x[i]), 0, nv[i] - 1)
            return x

        def update_weights():
            n = max(S["n_seen"], 1)
            rate = S["cnt"] / n
            mag = S["mag"] / np.maximum(S["cnt"], 1)
            mag_n = mag / (mag.max() + 1e-12)
            S["W"] = 1.0 + 4.0 * rate + 0.5 * mag_n + 3.0 * S["ema"]

        def phi(X):
            X = np.atleast_2d(X)
            Z = (X - lb) / span
            return np.hstack([Z, np.ones((X.shape[0], 1))])

        def fit_surrogate():
            if len(all_x) < max(30, 2 * (d + 1)):
                return
            X = np.array(all_x[-800:])
            V = np.array(all_v[-800:])
            P = phi(X)
            A = P.T @ P + 1e-2 * np.eye(P.shape[1])
            S["B"] = np.linalg.solve(A, P.T @ V)

        def pred_score(X):
            X = np.atleast_2d(X)
            if S["B"] is None or S["W"] is None:
                return np.zeros(X.shape[0])
            return np.maximum(phi(X) @ S["B"], 0.0) @ S["W"]

        def rank(r):
            if r["feas"]:
                return (0, r["f"])
            return (1, float(np.sum(S["W"] * r["viol"])))

        def evaluate(x):
            x = repair(np.asarray(x, dtype=float))
            k = tuple(np.round(x, 10))
            if k in cache:
                return cache[k]
            if self.used >= self.budget:
                return None
            f, g = func(x)
            self.used += 1
            f = float(f)
            g = np.nan_to_num(np.asarray(g, dtype=float).ravel(), nan=1e6,
                              posinf=1e6, neginf=0.0)
            if S["W"] is None:
                S["W"] = np.ones(len(g))
                S["cnt"] = np.zeros(len(g))
                S["mag"] = np.zeros(len(g))
                S["ema"] = np.zeros(len(g))
            v = np.maximum(g, 0.0)
            viol_flag = (v > 0).astype(float)
            S["cnt"] += viol_flag
            S["mag"] += v
            S["ema"] = 0.97 * S["ema"] + 0.03 * viol_flag
            S["n_seen"] += 1
            all_x.append(x.copy())
            all_v.append(v.copy())
            if S["n_seen"] <= 40 or S["n_seen"] % 20 == 0:
                update_weights()
            if S["n_seen"] >= 30 and S["n_seen"] % 20 == 0:
                fit_surrogate()
            if not np.isfinite(f):
                f = np.inf
            feas = (not np.any(v > 0)) and np.isfinite(f)
            r = {"x": x, "f": f, "viol": v, "feas": feas}
            cache[k] = r
            if feas:
                S["n_feas"] += 1
                feas_archive.append(r)
                if len(feas_archive) > 400:
                    feas_archive.sort(key=lambda z: z["f"])
                    del feas_archive[200:]
                if S["best"] is None or f < S["best"]["f"]:
                    S["best"] = r
            return r

        def sample(n):
            X = np.empty((n, d))
            if len(cont_idx):
                X[:, cont_idx] = np.random.uniform(lb[cont_idx], ub[cont_idx],
                                                   size=(n, len(cont_idx)))
            for i in int_idx:
                X[:, i] = np.random.randint(0, nv[i], size=n)
            return X

        def uniform_xover(p1, p2):
            mask = np.random.rand(d) < 0.5
            return np.where(mask, p1, p2)

        def mutate(x, sigma):
            y = x.copy()
            pm = min(0.5, 1.5 / d)
            mask = np.random.rand(d) < pm
            if not mask.any():
                mask[np.random.randint(d)] = True
            for i in np.where(mask)[0]:
                if is_bin[i]:
                    y[i] = 1.0 - y[i]
                elif is_cat[i]:
                    v = np.random.randint(nv[i] - 1)
                    if v >= int(round(y[i])):
                        v += 1
                    y[i] = v
                elif is_ord[i]:
                    if np.random.rand() < 0.7:
                        y[i] = y[i] + (1 if np.random.rand() < 0.5 else -1)
                    else:
                        y[i] = np.random.randint(nv[i])
                elif cont_mask[i]:
                    if np.random.rand() < 0.1:
                        step = 0.1 * np.random.standard_cauchy()
                    else:
                        step = sigma * np.random.randn()
                    y[i] = y[i] + step * cont_scale[i]
            return repair(y)

        def de_child(base, sigma):
            if len(feas_archive) >= 3:
                a = feas_archive[np.random.randint(len(feas_archive))]
                b = feas_archive[np.random.randint(len(feas_archive))]
                ax, bx = a["x"], b["x"]
            else:
                ax = base
                bx = base
            F = np.random.uniform(0.4, 0.9)
            y = base.copy()
            if len(cont_idx):
                y[cont_idx] = base[cont_idx] + F * (ax[cont_idx] - bx[cont_idx])
            for i in int_idx:
                if np.random.rand() < 0.3:
                    y[i] = ax[i]
            y = repair(y)
            return mutate(y, 0.5 * sigma)

        def coord_move(base, sigma):
            y = base.copy()
            k = 1 if np.random.rand() < 0.7 else 2
            for i in np.random.choice(d, size=k, replace=False):
                if cont_mask[i]:
                    y[i] = y[i] + 0.05 * np.random.randn() * cont_scale[i]
                elif is_bin[i]:
                    y[i] = 1.0 - y[i]
                elif is_cat[i]:
                    v = np.random.randint(nv[i] - 1)
                    if v >= int(round(y[i])):
                        v += 1
                    y[i] = v
                else:
                    y[i] = y[i] + (1 if np.random.rand() < 0.5 else -1)
            return repair(y)

        def make_child(op, p1, p2, best, sigma):
            if op == 0:
                if np.random.rand() < 0.7:
                    return mutate(uniform_xover(p1["x"], p2["x"]), sigma)
                return mutate(p1["x"], sigma)
            if op == 1:
                return de_child(p1["x"], sigma)
            if op == 2:
                other = best["x"] if (best is not None and
                                      (not p1["feas"] or np.random.rand() < 0.5)) else p2["x"]
                return mutate(uniform_xover(p1["x"], other), sigma)
            base = best["x"] if best is not None else p1["x"]
            return coord_move(base, sigma)

        def bisect_repair(child_r, best_r, steps=3):
            if best_r is None or child_r["feas"]:
                return child_r
            xb = best_r["x"]
            xi = child_r["x"]
            lo, hi = 0.0, 1.0
            res = None
            for _ in range(steps):
                if self.used >= self.budget:
                    break
                t = 0.5 * (lo + hi)
                r = evaluate(xb + t * (xi - xb))
                if r is None:
                    break
                if r["feas"]:
                    lo = t
                    res = r
                else:
                    hi = t
            return res if res is not None else child_r

        def dedupe_sort(pool, cap):
            pool = sorted(pool, key=rank)
            out, seen = [], set()
            for r in pool:
                k = tuple(np.round(r["x"], 10))
                if k in seen:
                    continue
                seen.add(k)
                out.append(r)
                if len(out) >= cap:
                    break
            return out

        n_ops = 4
        op_score = np.ones(n_ops)

        def choose_op():
            p = op_score / op_score.sum()
            p = 0.9 * p + 0.1 / n_ops
            return np.random.choice(n_ops, p=p / p.sum())

        mu = max(10, 3 * d)
        lam = 2 * mu
        init_n = max(1, min(max(2 * mu, 20), self.budget // 3 if self.budget >= 3 else self.budget))
        pop = []
        for x in sample(init_n):
            r = evaluate(x)
            if r is None:
                break
            pop.append(r)
        pop = dedupe_sort(pop, mu)

        sigma = 0.2
        stall = 0
        last_best = np.inf
        stall_limit = 15 + d

        while self.used < self.budget and len(pop) > 0:
            children = []
            succ = 0
            med = pop[len(pop) // 2]
            feas_ratio = S["n_feas"] / max(S["n_seen"], 1)
            p_rep = float(np.clip(0.1 + 0.5 * (1.0 - feas_ratio), 0.05, 0.4))
            K = 3 if S["B"] is not None else 1
            for _ in range(lam):
                if self.used >= self.budget:
                    break
                op = choose_op()
                i1 = min(np.random.randint(len(pop)), np.random.randint(len(pop)))
                i2 = min(np.random.randint(len(pop)), np.random.randint(len(pop)))
                p1, p2 = pop[i1], pop[i2]
                best = S["best"]

                cands = [make_child(op, p1, p2, best, sigma) for _ in range(K)]
                if K > 1 and np.random.rand() < 0.8:
                    scores = pred_score(np.array(cands))
                    child = cands[int(np.argmin(scores))]
                else:
                    child = cands[np.random.randint(len(cands))]

                r = evaluate(child)
                if r is None:
                    break
                if (not r["feas"]) and best is not None and np.random.rand() < p_rep:
                    r2 = bisect_repair(r, S["best"])
                    if r2 is not r:
                        r = r2
                children.append(r)
                reward = (1.0 if rank(r) < rank(med) else 0.0)
                reward += (1.0 if rank(r) < rank(p1) else 0.0)
                reward *= 0.5
                op_score[op] = 0.9 * op_score[op] + 0.1 * (0.05 + reward)
                if rank(r) < rank(p1):
                    succ += 1

            if children:
                rate = succ / len(children)
                sigma *= 1.2 if rate > 0.2 else 0.85
                sigma = float(np.clip(sigma, 0.005, 0.5))

            pop = dedupe_sort(pop + children, mu)
            if not pop:
                break

            cur_best = S["best"]["f"] if S["best"] is not None else np.inf
            if cur_best < last_best - 1e-12:
                last_best = cur_best
                stall = 0
            else:
                stall += 1

            if stall >= stall_limit and self.used < self.budget:
                if S["best"] is not None:
                    cur = S["best"]
                    for _ in range(2 * d + 10):
                        if self.used >= self.budget:
                            break
                        new = evaluate(coord_move(cur["x"], sigma))
                        if new is None:
                            break
                        if rank(new) < rank(cur):
                            cur = new
                    elite = cur
                else:
                    elite = pop[0]
                new_pop = [elite]
                if len(feas_archive) > 0:
                    k = min(len(feas_archive), mu // 3)
                    for idx in np.random.choice(len(feas_archive), size=k, replace=False):
                        new_pop.append(feas_archive[idx])
                for x in sample(max(0, mu - len(new_pop))):
                    r = evaluate(x)
                    if r is None:
                        break
                    new_pop.append(r)
                pop = dedupe_sort(new_pop, mu)
                sigma = 0.3
                stall = 0
                last_best = S["best"]["f"] if S["best"] is not None else np.inf

        if S["best"] is None:
            return np.inf, None
        return S["best"]["f"], S["best"]["x"].copy()